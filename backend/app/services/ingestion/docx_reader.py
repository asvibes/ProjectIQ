"""DOCX reader: paragraphs, headings and table rows, in document order.

Returns an :class:`~app.services.ingestion.sanitizer.ExtractedDocument` like every other
reader. The body is walked element by element (not ``document.paragraphs`` then
``document.tables``), so a table appears exactly where it sits between paragraphs.

Segments
--------
* paragraph -> ``SegmentKind.PARAGRAPH`` (or ``HEADING`` for ``Title`` / ``Heading N``
  styles, with ``heading_level`` 0 / N); ``location_ref="paragraph N"`` where N counts the
  non-empty paragraphs in the body, in order.
* table row -> ``SegmentKind.TABLE_ROW``; ``cells`` holds one entry per grid column (merged
  continuation cells are ``""`` so columns stay aligned), ``text`` is the cells joined with
  ``" | "``, ``location_ref="table T, row R"`` (T counts top-level tables, R counts every
  row including empty ones). Nested tables are flattened into the cell that contains them.
  Content controls (``w:sdt``) are read like ordinary content.

Tracked changes: inserted text is kept and deleted text is dropped, and a warning says so.

Not extracted (listed in ``metadata["parts_not_extracted"]``): headers and footers,
footnotes and endnotes, comments, text boxes, equations, images. Automatic list / clause
numbering ("1.1", "(a)") is generated by Word at render time and is not in the file's text,
so it is not reproduced; a warning is added when such paragraphs exist.

Safety (the file is untrusted): size and extension are checked by ``load_source``, the zip
container by ``ensure_ooxml`` (entry count, expansion size, compression ratio, unsafe
paths) *before* parsing; a file carrying a VBA project is refused; nothing is executed,
no macros are run, and no external links, templates or linked images are followed.
Sanitising is applied but is *not* a defence against prompt injection: instructions written
in the document are returned verbatim, as text.
"""
from __future__ import annotations

import io
import re
import zipfile
from typing import Iterator, Optional

import docx
from docx.oxml.ns import qn
from docx.text.paragraph import Paragraph

from app.services.ingestion.sanitizer import (
    MAX_FILE_BYTES,
    CorruptDocumentError,
    ExtractedDocument,
    ExtractionStatus,
    IngestionError,
    ResourceLimitError,
    SanitizationReport,
    SegmentKind,
    Source,
    TextSegment,
    UnsupportedFormatError,
    ensure_ooxml,
    load_source,
    sanitize_text_with_report,
)

__all__ = ["MAX_EXTRACTED_CHARS", "read_docx"]

MAX_EXTRACTED_CHARS = 20_000_000

_W_P = qn("w:p")
_W_TBL = qn("w:tbl")
_W_TR = qn("w:tr")
_W_TC = qn("w:tc")
_W_SDT = qn("w:sdt")
_W_SDT_CONTENT = qn("w:sdtContent")
_W_T = qn("w:t")
_W_TAB = qn("w:tab")
_W_BR = qn("w:br")
_W_CR = qn("w:cr")
_W_NO_BREAK_HYPHEN = qn("w:noBreakHyphen")
_W_PPR = qn("w:pPr")
_W_NUM_PR = qn("w:numPr")
_W_NUM_ID = qn("w:numId")
_W_TC_PR = qn("w:tcPr")
_W_GRID_SPAN = qn("w:gridSpan")
_W_V_MERGE = qn("w:vMerge")
_W_VAL = qn("w:val")
_W_TYPE = qn("w:type")
_W_INS = qn("w:ins")
_W_DEL = qn("w:del")
_W_MOVE_FROM = qn("w:moveFrom")
_W_TXBX_CONTENT = qn("w:txbxContent")
_MC_FALLBACK = "{http://schemas.openxmlformats.org/markup-compatibility/2006}Fallback"
# Content that must not be read as part of the visible text of a paragraph.
_SKIPPED_IN_PARAGRAPH = frozenset({_W_PPR, _W_DEL, _W_MOVE_FROM, _W_TXBX_CONTENT, _MC_FALLBACK})

_HEADING_STYLE_RE = re.compile(r"^Heading (\d{1,2})$")
_MAX_GRID_SPAN = 1_000  # guards against a crafted gridSpan allocating huge tuples

PARTS_NOT_EXTRACTED = [
    "headers_and_footers",
    "footnotes_and_endnotes",
    "comments",
    "text_boxes",
    "equations",
    "images",
]


def _iter_blocks(parent) -> Iterator[tuple[str, object]]:
    """Yield ``("p", element)`` / ``("tbl", element)`` children in order, entering content controls."""
    for child in parent.iterchildren():
        tag = child.tag
        if tag == _W_P:
            yield "p", child
        elif tag == _W_TBL:
            yield "tbl", child
        elif tag == _W_SDT:
            content = child.find(_W_SDT_CONTENT)
            if content is not None:
                yield from _iter_blocks(content)


def _paragraph_text(p) -> str:
    """Visible text of a ``w:p``: inserted text kept, deleted text and text-box content skipped."""
    parts: list[str] = []

    def walk(element) -> None:
        for child in element:
            tag = child.tag
            if tag in _SKIPPED_IN_PARAGRAPH:
                continue
            if tag == _W_T:
                parts.append(child.text or "")
            elif tag == _W_TAB:
                parts.append("\t")
            elif tag == _W_CR:
                parts.append("\n")
            elif tag == _W_BR:
                # Page and column breaks are layout, not text.
                if child.get(_W_TYPE) in (None, "textWrapping"):
                    parts.append("\n")
            elif tag == _W_NO_BREAK_HYPHEN:
                parts.append("-")
            else:
                walk(child)

    walk(p)
    return "".join(parts)


def _has_auto_numbering(p) -> bool:
    ppr = p.find(_W_PPR)
    if ppr is None:
        return False
    num_pr = ppr.find(_W_NUM_PR)
    if num_pr is None:
        return False
    num_id = num_pr.find(_W_NUM_ID)
    return num_id is None or num_id.get(_W_VAL) != "0"  # numId 0 means "no numbering"


def _style_has_numbering(paragraph: Paragraph) -> bool:
    """True if the paragraph's own style (one level, no ``basedOn`` chain) turns on numbering."""
    try:
        style = paragraph.style
        ppr = style.element.find(_W_PPR) if style is not None else None
        return ppr is not None and ppr.find(_W_NUM_PR) is not None
    except Exception:  # noqa: BLE001 - a dangling style reference must not fail extraction
        return False


def _heading_level(paragraph: Paragraph) -> Optional[int]:
    try:
        style = paragraph.style
        name = style.name if style is not None else None
    except Exception:  # noqa: BLE001 - a dangling style reference must not fail extraction
        return None
    if not name:
        return None
    if name == "Title":
        return 0
    match = _HEADING_STYLE_RE.match(name)
    return int(match.group(1)) if match else None


def _block_texts(parent) -> Iterator[str]:
    """Raw text of every paragraph under ``parent``; nested tables are flattened."""
    for kind, element in _iter_blocks(parent):
        if kind == "p":
            yield _paragraph_text(element)
        else:
            for tr in element.iterchildren(_W_TR):
                for tc in tr.iterchildren(_W_TC):
                    yield from _block_texts(tc)


def _grid_span(tc_pr) -> int:
    if tc_pr is None:
        return 1
    span = tc_pr.find(_W_GRID_SPAN)
    if span is None:
        return 1
    try:
        return max(1, min(int(span.get(_W_VAL, "1")), _MAX_GRID_SPAN))
    except ValueError:
        return 1


def _is_vertical_continuation(tc_pr) -> bool:
    if tc_pr is None:
        return False
    merge = tc_pr.find(_W_V_MERGE)
    return merge is not None and merge.get(_W_VAL, "continue") != "restart"


def _open_document(data: bytes):
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            if any(n.lower().endswith("vbaproject.bin") for n in archive.namelist()):
                raise UnsupportedFormatError(
                    "The document contains a VBA macro project; macro-enabled files are not accepted."
                )
        return docx.Document(io.BytesIO(data))
    except IngestionError:
        raise
    except MemoryError as exc:
        raise ResourceLimitError("The DOCX needs more memory to parse than is allowed.") from exc
    except Exception as exc:  # noqa: BLE001 - python-docx raises many types on malformed packages
        raise CorruptDocumentError(
            f"The DOCX file is corrupt or could not be parsed ({type(exc).__name__})."
        ) from exc


def read_docx(
    source: Source,
    filename: Optional[str] = None,
    *,
    max_bytes: int = MAX_FILE_BYTES,
) -> ExtractedDocument:
    """Extract paragraphs, headings and table rows from a ``.docx`` file, in body order.

    Raises :class:`IngestionError` subclasses (``UnsupportedFormatError``,
    ``CorruptDocumentError``, ``ResourceLimitError``); never returns an "error result".
    A document with no text is returned with ``ExtractionStatus.EMPTY``.
    """
    data, name = load_source(source, filename, (".docx",), max_bytes)
    ensure_ooxml(data, "word/document.xml", "DOCX")
    document = _open_document(data)

    report = SanitizationReport()
    segments: list[TextSegment] = []
    counters = {"paragraph": 0, "table": 0, "table_rows": 0, "headings": 0, "numbered": 0, "chars": 0}

    def clean(raw: str) -> str:
        text, part = sanitize_text_with_report(raw)
        report.merge(part)
        counters["chars"] += len(text)
        if counters["chars"] > MAX_EXTRACTED_CHARS:
            raise ResourceLimitError(
                f"The document text exceeds the limit of {MAX_EXTRACTED_CHARS} characters."
            )
        return text

    try:
        body = document.element.body
        for kind, element in _iter_blocks(body):
            if kind == "p":
                text = clean(_paragraph_text(element))
                if not text:
                    continue
                counters["paragraph"] += 1
                paragraph = Paragraph(element, document._body)
                if _has_auto_numbering(element) or _style_has_numbering(paragraph):
                    counters["numbered"] += 1
                level = _heading_level(paragraph)
                if level is not None:
                    counters["headings"] += 1
                segments.append(
                    TextSegment(
                        text=text,
                        kind=SegmentKind.HEADING if level is not None else SegmentKind.PARAGRAPH,
                        source_filename=name,
                        location_ref=f"paragraph {counters['paragraph']}",
                        heading_level=level,
                    )
                )
                continue

            counters["table"] += 1
            for row_number, tr in enumerate(element.iterchildren(_W_TR), start=1):
                counters["table_rows"] += 1
                cells: list[str] = []
                for tc in tr.iterchildren(_W_TC):
                    tc_pr = tc.find(_W_TC_PR)
                    if _is_vertical_continuation(tc_pr):
                        value = ""
                    else:
                        raw = " ".join(t for t in _block_texts(tc) if t.strip())
                        value = " ".join(clean(raw).split())
                    cells.append(value)
                    cells.extend([""] * (_grid_span(tc_pr) - 1))
                while cells and not cells[-1]:
                    cells.pop()
                if not any(cells):
                    continue
                segments.append(
                    TextSegment(
                        text=" | ".join(cells),
                        kind=SegmentKind.TABLE_ROW,
                        source_filename=name,
                        location_ref=f"table {counters['table']}, row {row_number}",
                        cells=tuple(cells),
                    )
                )

        insertions = sum(1 for _ in body.iter(_W_INS))
        deletions = sum(1 for _ in body.iter(_W_DEL))
        has_text_boxes = next(body.iter(_W_TXBX_CONTENT), None) is not None
    except IngestionError:
        raise
    except MemoryError as exc:
        raise ResourceLimitError("The DOCX needs more memory to read than is allowed.") from exc
    except Exception as exc:  # noqa: BLE001 - hostile XML can fail in many ways
        raise CorruptDocumentError(
            f"The DOCX content could not be read ({type(exc).__name__})."
        ) from exc

    warnings = report.warnings()
    if insertions or deletions:
        warnings.append(
            f"The document contains tracked changes ({insertions} insertion(s), {deletions} "
            "deletion(s)). The extracted text keeps inserted text and omits deleted text."
        )
    if has_text_boxes:
        warnings.append("The document contains text boxes; their text was not extracted.")
    if counters["numbered"]:
        warnings.append(
            f"{counters['numbered']} paragraph(s) use automatic numbering. Word generates those "
            "numbers (for example clause numbers) at render time, so they are not in the "
            "extracted text."
        )

    return ExtractedDocument(
        filename=name,
        file_type="docx",
        status=ExtractionStatus.OK if segments else ExtractionStatus.EMPTY,
        segments=segments,
        page_count=None,
        warnings=warnings,
        metadata={
            "paragraph_count": counters["paragraph"],
            "heading_count": counters["headings"],
            "table_count": counters["table"],
            "table_row_count": counters["table_rows"],
            "auto_numbered_paragraphs": counters["numbered"],
            "tracked_changes": bool(insertions or deletions),
            "parts_not_extracted": list(PARTS_NOT_EXTRACTED),
            "sanitization": report.as_dict(),
        },
    )