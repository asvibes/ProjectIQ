"""Evidence-grounded drafting of the decision briefing (``briefing_v1``).

The drafter receives **already-extracted, already-analysed data** (requirements, gaps, risks,
financial results and facts), not raw documents. Every item gets a reference id (the
requirement code, gap id, risk code, ``FACT-<id>`` or ``FIN-<name>``) and the model must cite
those ids for every claim.

Validation of the model's draft (the model's draft is never stored or shown as-is):
* The JSON must match a strict schema (title, sections with heading / body / references,
  assumptions, missing information).
* References are checked against the supplied ids. Unknown ids are removed; a section left with
  no valid reference is dropped, as is a section whose text mentions an id-like token that was
  not supplied (for example ``REQ-099``).
* Figures (two or more digits, or decimals) in any text must already appear in the supplied data.
  Numbers come from the deterministic finance and analysis modules; a section, assumption or
  title containing an unsupplied figure is dropped. Nothing is calculated here.
* Assumptions are kept apart from evidence-backed sections and are labelled as assumptions in
  the Markdown. Missing information is listed separately.
* The Markdown adds deterministic notes the model cannot remove: a decision-support disclaimer,
  and the list of cited items whose verification status is not ``Verified``.

If nothing usable survives, or the model is unavailable, an ``OllamaError`` is raised and no
draft is returned. This module does not touch the database; :meth:`Briefing.to_artifact_values`
returns the column values for an ``Artifact`` of type ``briefing`` for the caller to store.
"""
from __future__ import annotations

import json
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from datetime import date, datetime
from decimal import Decimal
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, ValidationError, field_validator

from app.models.artifact import ArtifactFormat, ArtifactType
from app.services.ai.ollama_client import (
    OllamaClient,
    OllamaResponseError,
    fence_untrusted_json,
    get_ollama_client,
    load_prompt,
    provenance,
    unsupported_numbers,
)
from app.services.errors import ServiceError

__all__ = ["Briefing", "BriefingContext", "BriefingSection", "draft_briefing"]

PROMPT_NAME = "briefing_v1"
MAX_PAYLOAD_CHARS = 14_000
MAX_FIELD_CHARS = 400
MAX_QUOTE_CHARS = 300
MAX_SECTIONS = 12

DISCLAIMER = (
    "Decision-support draft generated by a local AI model from the project data listed below. "
    "It must be reviewed by a person and is not a bid decision."
)

_FIELDS: dict[str, tuple[str, ...]] = {
    "requirements": (
        "code", "description", "category", "is_mandatory", "deadline", "match_status", "verification_status",
        "evidence_summary", "missing_evidence", "quotation",
    ),
    "gaps": (
        "gap_id", "gap_type", "severity", "title", "detail", "blocking", "requirement_code", "match_status",
        "what_would_close_it", "requirement_reviewed",
    ),
    "risks": (
        "code", "title", "category", "status", "probability", "impact", "score", "band", "verification_status",
        "quotation",
    ),
    "facts": ("label", "value", "normalized_value", "fact_type", "verification_status", "quotation"),
}
_PROJECT_FIELDS = ("name", "description", "status", "currency", "default_currency")


@dataclass(frozen=True)
class BriefingContext:
    """Inputs for a briefing. Items may be mappings, objects with ``to_dict()`` (``Gap``,
    ``RiskAssessment`` ...) or ORM rows; only whitelisted fields are read.

    ``financials`` maps a name to a value or small mapping computed by ``services/finance``."""

    project: Any = None
    requirements: Sequence[Any] = ()
    gaps: Sequence[Any] = ()
    risks: Sequence[Any] = ()
    facts: Sequence[Any] = ()
    financials: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class BriefingSection:
    heading: str
    body: str
    references: tuple[str, ...]


@dataclass(frozen=True)
class Briefing:
    title: str
    sections: tuple[BriefingSection, ...]
    assumptions: tuple[str, ...]
    missing_information: tuple[str, ...]
    unverified_references: tuple[str, ...]  # cited items whose status is not "Verified"
    warnings: tuple[str, ...]
    markdown: str
    model: str
    prompt: str = PROMPT_NAME
    generated_by: Optional[str] = None

    def to_artifact_values(self) -> dict[str, Any]:
        """Column values for an ``Artifact`` (``project_id`` and ``version`` are the caller's)."""
        return {
            "artifact_type": ArtifactType.BRIEFING,
            "file_format": ArtifactFormat.MARKDOWN,
            "title": self.title[:200],
            "content": self.markdown,
            "generated_by": self.generated_by,
            "extra": {
                "references": sorted({r for s in self.sections for r in s.references}),
                "unverified_references": list(self.unverified_references),
                "status": "draft_requires_review",
            },
        }


# ---------------------------------------------------------------------------
# Strict schema for the model's draft
# ---------------------------------------------------------------------------
class _RawSection(BaseModel):
    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    heading: str
    body: str
    references: list[str] = []

    @field_validator("heading")
    @classmethod
    def _heading(cls, value: str) -> str:
        if not value or len(value) > 200:
            raise ValueError("bad heading")
        return value

    @field_validator("body")
    @classmethod
    def _body(cls, value: str) -> str:
        if not value or len(value) > 4000:
            raise ValueError("bad body")
        return value

    @field_validator("references", mode="before")
    @classmethod
    def _refs(cls, value: Any) -> Any:
        return [r.strip() for r in value if isinstance(r, str)] if isinstance(value, list) else []


class _RawBriefing(BaseModel):
    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    title: str
    sections: list[Any]
    assumptions: list[str] = []
    missing_information: list[str] = []

    @field_validator("sections")
    @classmethod
    def _sections(cls, value: list[Any]) -> list[Any]:
        if not value or len(value) > MAX_SECTIONS:
            raise ValueError("no sections or too many")
        return value

    @field_validator("assumptions", "missing_information", mode="before")
    @classmethod
    def _lines(cls, value: Any) -> Any:
        if not isinstance(value, list):
            return []
        return [v.strip() for v in value if isinstance(v, str) and v.strip()][:10]


# ---------------------------------------------------------------------------
# Building the evidence index and the payload
# ---------------------------------------------------------------------------
def _plain(value: Any) -> Any:
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, str):
        return value if len(value) <= MAX_FIELD_CHARS else value[:MAX_FIELD_CHARS] + " [truncated]"
    if isinstance(value, Mapping):
        return {str(k): _plain(v) for k, v in list(value.items())[:20]}
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in list(value)[:20]]
    return value


def _read(obj: Any, name: str) -> Any:
    if isinstance(obj, Mapping):
        return obj.get(name)
    return getattr(obj, name, None)


def _item(obj: Any, fields: tuple[str, ...]) -> dict[str, Any]:
    source: Any = obj
    if not isinstance(obj, Mapping) and callable(getattr(obj, "to_dict", None)):
        source = obj.to_dict()
    out = {}
    for name in fields:
        value = _read(source, name)
        if value is not None:
            out[name] = _plain(value)
    if "quotation" in out and isinstance(out["quotation"], str):
        out["quotation"] = out["quotation"][:MAX_QUOTE_CHARS]
    return out


def _ref_of(kind: str, obj: Any, item: dict[str, Any]) -> Optional[str]:
    if kind == "gaps":
        value = item.get("gap_id")
    elif kind == "facts":
        explicit = _read(obj, "ref")
        value = explicit or (f"FACT-{_read(obj, 'id')}" if _read(obj, "id") is not None else None)
    else:
        value = item.get("code")
    return str(value).strip() if value not in (None, "") else None


def _status_of(kind: str, item: dict[str, Any]) -> str:
    """Verification status used for the briefing's "not verified" note."""
    if kind == "gaps":  # a rule-based finding; it is as reviewed as the requirement behind it
        reviewed = item.get("requirement_reviewed")
        return "Computed" if reviewed is None else ("Verified" if reviewed else "Requires review")
    return item.get("verification_status") or "Unknown"


@dataclass
class _Index:
    payload: dict[str, Any]
    statuses: dict[str, str]  # ref -> verification status ("Verified", "Computed", "Unknown", ...)
    omitted: int


def _build_index(context: BriefingContext) -> _Index:
    statuses: dict[str, Optional[str]] = {}
    payload: dict[str, Any] = {}
    budget = MAX_PAYLOAD_CHARS
    omitted = 0

    def take(entry: Any) -> bool:
        nonlocal budget
        size = len(json.dumps(entry, ensure_ascii=True, default=str))
        if size > budget:
            return False
        budget -= size
        return True

    if context.project is not None:
        project = _item(context.project, _PROJECT_FIELDS)
        if project:
            payload["project"] = project
            take(project)

    financials = []
    for name, value in context.financials.items():
        ref = f"FIN-{name}"
        if ref in statuses:
            raise ValueError(f"duplicate reference {ref}")
        entry = {"ref": ref, "name": str(name), "value": _plain(value)}
        if take(entry):
            statuses[ref] = "Computed"  # produced by the deterministic finance modules
            financials.append(entry)
        else:
            omitted += 1
    if financials:
        payload["financials"] = financials

    for kind in ("gaps", "risks", "requirements", "facts"):
        entries = []
        for obj in getattr(context, kind):
            item = _item(obj, _FIELDS[kind])
            ref = _ref_of(kind, obj, item)
            if ref is None:
                raise ValueError(f"every {kind[:-1]} needs a reference id")
            if ref in statuses:
                raise ValueError(f"duplicate reference {ref}")
            entry = {"ref": ref, **item}
            if take(entry):
                statuses[ref] = _status_of(kind, item)
                entries.append(entry)
            else:
                omitted += 1
        if entries:
            payload[kind] = entries

    if omitted:
        payload["omitted_items"] = omitted
    return _Index(payload, statuses, omitted)


# ---------------------------------------------------------------------------
# Validation and rendering
# ---------------------------------------------------------------------------
def _ref_like_tokens(text: str, prefixes: set[str]) -> set[str]:
    return {t for t in re.findall(r"\b([A-Z]{2,6}-[A-Za-z0-9_]+)\b", text) if t.split("-", 1)[0] in prefixes}


def _render(title: str, sections: Sequence[BriefingSection], assumptions: Sequence[str],
            missing: Sequence[str], unverified: Sequence[str]) -> str:
    lines = [f"# {title}", "", f"_{DISCLAIMER}_", ""]
    for section in sections:
        lines += [f"## {section.heading}", "", section.body, "", f"Sources: {', '.join(section.references)}", ""]
    if assumptions:
        lines += ["## Assumptions (not taken from the project data)", ""] + [f"- {a}" for a in assumptions] + [""]
    if missing:
        lines += ["## Missing information", ""] + [f"- {m}" for m in missing] + [""]
    if unverified:
        lines += [
            "## Verification note",
            "",
            "The following cited items have not been verified by a person: " + ", ".join(unverified) + ".",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def draft_briefing(context: BriefingContext, *, client: Optional[OllamaClient] = None) -> Briefing:
    """Draft a decision briefing from analysed project data.

    Raises ``ServiceError`` (422) if there is no data to draft from, ``ValueError`` for items
    without a usable reference id, and ``OllamaError`` if the model is unavailable, times out,
    or returns nothing usable."""
    index = _build_index(context)
    if not index.statuses:
        raise ServiceError(422, "There is no analysed project data to draft a briefing from.")

    system = load_prompt(PROMPT_NAME)
    client = client or get_ollama_client()
    prompt = "Draft the briefing from this data.\n\n" + fence_untrusted_json(index.payload, label="PROJECT DATA")
    data, result = client.generate_json(prompt, system=system, max_output_tokens=2500)
    try:
        raw = _RawBriefing.model_validate(data)
    except ValidationError as exc:
        raise OllamaResponseError("The local AI model's draft was not in the expected format.") from exc

    known = set(index.statuses)
    prefixes = {r.split("-", 1)[0] for r in known if "-" in r}
    allowed_numbers: list[Any] = [index.payload, sorted(known)]
    warnings: list[str] = []
    if index.omitted:
        warnings.append(f"{index.omitted} item(s) did not fit and were not sent to the model.")

    sections: list[BriefingSection] = []
    dropped = 0
    for candidate in raw.sections:
        try:
            section = _RawSection.model_validate(candidate)
        except ValidationError:
            dropped += 1
            continue
        refs = tuple(dict.fromkeys(r for r in section.references if r in known))
        text = f"{section.heading} {section.body}"
        if (
            not refs
            or _ref_like_tokens(text, prefixes) - known
            or unsupported_numbers(text, *allowed_numbers)
        ):
            dropped += 1
            continue
        sections.append(BriefingSection(section.heading, section.body, refs))
    if dropped:
        warnings.append(f"{dropped} section(s) were removed because they were not supported by the supplied data.")
    if not sections:
        raise OllamaResponseError("The local AI model's draft had no section supported by the supplied data.")

    def clean(lines: Sequence[str], what: str) -> tuple[str, ...]:
        kept = tuple(
            line for line in lines
            if not unsupported_numbers(line, *allowed_numbers) and not (_ref_like_tokens(line, prefixes) - known)
        )
        if len(kept) < len(lines):
            warnings.append(f"{len(lines) - len(kept)} {what} line(s) were removed because they contained unsupported figures or references.")
        return kept

    assumptions = clean(raw.assumptions, "assumption")
    missing = clean(raw.missing_information, "missing-information")
    title = raw.title if raw.title and len(raw.title) <= 200 and not unsupported_numbers(raw.title, *allowed_numbers) else "Tender decision briefing"

    cited = {r for s in sections for r in s.references}
    unverified = tuple(sorted(r for r in cited if index.statuses.get(r) not in ("Verified", "Computed")))
    return Briefing(
        title=title,
        sections=tuple(sections),
        assumptions=assumptions,
        missing_information=missing,
        unverified_references=unverified,
        warnings=tuple(warnings),
        markdown=_render(title, sections, assumptions, missing, unverified),
        model=result.model,
        generated_by=provenance(PROMPT_NAME, client.model),
    )
